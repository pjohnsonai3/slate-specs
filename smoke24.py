import os
APP='file://'+os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','slate-specs.html'))
FX=os.environ.get('FX','/home/claude/slate-specs/test')
from playwright.sync_api import sync_playwright
errs=[]
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
    ctx=b.new_context(viewport={'width':1400,'height':1000}); pg=ctx.new_page()
    pg.on('pageerror',lambda e:errs.append(str(e)+' @ '+str(e.stack)[:300])); pg.on('dialog',lambda d:d.accept())
    pg.route('https://fonts.googleapis.com/**',lambda r:r.abort()); pg.route('https://*.supabase.co/**',lambda r:r.abort())
    pg.goto(APP); pg.wait_for_timeout(1200)
    if pg.locator('#gate').count(): pg.click('[data-act=offline]')
    pg.click('[data-act=nav][data-v=settings]')
    pg.set_input_files('#stdfile',[FX+'/AIA_A201-2017_General_Conditions.pdf',FX+'/Appendix_Notes.pdf']); pg.wait_for_timeout(800)
    print('saved rows:',pg.locator('[data-sdlabel]').count())
    pg.fill('[data-sdlabel="0"]','AIA A201-2017 General Conditions'); pg.fill('[data-sdurl="0"]','https://www.aiacontracts.com'); pg.wait_for_timeout(200)
    pg.check('[data-sddef="1"]'); pg.wait_for_timeout(100)
    print('link shown:',pg.locator('a:has-text("Open")').count(),'| stored:',pg.evaluate("JSON.parse(localStorage.getItem('ss1_stddocs')).map(function(d){return d.label+'|'+d.url+'|'+d.def})"))
    pg.reload(); pg.wait_for_timeout(900)
    if pg.locator('#gate').count(): pg.click('[data-act=offline]')
    pg.click('[data-act=newproj]'); pg.fill('[data-pf=name]','Std Docs Test'); pg.click('[data-act=wiznext]'); pg.fill('[data-pf=contractForm]','AIA A201-2017'); pg.click('[data-act=wiznext]'); pg.select_option('#npstart',value='s:1'); pg.click('[data-act=createproj]'); pg.wait_for_timeout(400)
    pg.click('[data-act=tab][data-t=export]'); pg.click('[data-act=mergeopen]'); pg.wait_for_selector('[data-stdpick]',timeout=30000); pg.wait_for_timeout(1200)
    print('prechecked:',pg.evaluate("[...document.querySelectorAll('[data-stdpick]')].map(c=>c.checked)"))
    pg.click('[data-act=sdpickadd]'); pg.wait_for_timeout(800)
    print('merge rows:',pg.evaluate("[...document.querySelectorAll('[data-mglabel]')].map(i=>i.value)"),'| positions:',pg.evaluate("[...document.querySelectorAll('[data-mgpos]')].map(s=>s.options[s.selectedIndex].text)"))
    pg.click('[data-act=sdpickadd]'); pg.wait_for_timeout(400); print('no duplicates:',pg.locator('[data-mglabel]').count())
    pg.click('[data-act=closemodal]'); pg.click('[data-act=nav][data-v=settings]'); pg.click('[data-act=sddel] >> nth=1'); pg.wait_for_timeout(300)
    print('after delete rows:',pg.locator('[data-sdlabel]').count())
    b.close()
print('ERRORS',errs)
